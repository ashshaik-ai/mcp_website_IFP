/* Generates src/content/lesson-index.ts: just enough about each lesson to
   render the index card, and nothing more.

   LessonIndex is a client component and imported the full lessons module for
   the sake of a title, an intro line and three counts. That pulled all 75
   lessons, in both languages, into the JavaScript of every portal page. Once
   the lessons were rewritten to real length it came to roughly 400 KB gzipped
   per portal, for content the page never displays.

   Run as part of prebuild, alongside the search index.
   Usage: node --experimental-strip-types scripts/build-lesson-index.mjs */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/content/lesson-index.ts");

const { lessons } = await import("../src/content/all-lessons.ts");

/* The intro is only ever shown clamped to two lines, so there is no reason to
   ship the whole paragraph. Cut on a word boundary so it does not end mid-word. */
const CLAMP = 160;
const clip = (s) => {
  if (!s || s.length <= CLAMP) return s ?? "";
  const cut = s.slice(0, CLAMP);
  const space = cut.lastIndexOf(" ");
  return (space > CLAMP * 0.6 ? cut.slice(0, space) : cut).trimEnd() + "…";
};

const entries = lessons.map((l) => ({
  portal: l.portal,
  slug: l.slug,
  title: l.title,
  intro: l.intro ? { te: clip(l.intro.te), en: clip(l.intro.en) } : null,
  sections: l.sections.length,
  quiz: l.quiz.length,
  faqs: l.faqs.length,
}));

const file = `/* AUTO-GENERATED by scripts/build-lesson-index.mjs — do not edit by hand.

   The minimum LessonIndex needs to render a card: a title, a clipped intro and
   three counts. Importing the full lessons module into that client component
   put every lesson's complete text into the JavaScript of every portal page.

   ${entries.length} lessons across ${new Set(entries.map((e) => e.portal)).size} portals. */

export type Bi = { te: string; en: string };

export type LessonSummary = {
  portal: string;
  slug: string;
  title: Bi;
  intro: Bi | null;
  sections: number;
  quiz: number;
  faqs: number;
};

export const lessonSummaries: LessonSummary[] = ${JSON.stringify(entries, null, 2)};

export const summariesByPortal = (portal: string) =>
  lessonSummaries.filter((l) => l.portal === portal);
`;

fs.writeFileSync(OUT, file, "utf8");

const kb = (Buffer.byteLength(file) / 1024).toFixed(0);
console.log(`Wrote src/content/lesson-index.ts — ${entries.length} lessons, ${kb} KB`);
