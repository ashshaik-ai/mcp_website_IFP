/* Generates src/content/assessment-bank.ts: the end-of-portal assessment.

   Every portal teaches its lessons and then stops. The platforms this was
   measured against — Coursera, edX, Udemy, LinkedIn Learning — all close a
   course with something that asks whether it landed, across the whole course
   rather than one lesson at a time.

   The questions already exist: each lesson carries a quiz and its sections
   carry checks. This gathers them per portal, caps the set at twelve, and
   spreads the pick across the lessons so the assessment covers the course
   rather than hammering whichever lesson happened to have the most questions.

   Ships as its own module, not through the lesson index, so a portal page that
   never opens the assessment does not carry it. Run as part of prebuild.
   Usage: node --experimental-strip-types scripts/build-assessment-bank.mjs */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/content/assessment-bank.ts");

const { lessons } = await import("../src/content/all-lessons.ts");

const MAX = 12;

const byPortal = new Map();
for (const l of lessons) {
  if (!byPortal.has(l.portal)) byPortal.set(l.portal, []);
  byPortal.get(l.portal).push(l);
}

/* One question, flattened to what the assessment renders. */
const shape = (q, lesson) => ({
  q: q.question,
  options: q.options,
  answer: q.answer,
  from: { slug: lesson.slug, title: lesson.title },
});

/* Round-robin across the lessons: take the first question of each, then the
   second of each, and so on. A portal with one long lesson and three short
   ones then still gets asked about all four. */
const gather = (list) => {
  const pools = list.map((l) => [
    ...l.quiz.map((q) => shape(q, l)),
    ...l.sections.filter((s) => s.check).map((s) => shape(s.check, l)),
  ]);
  const out = [];
  for (let round = 0; out.length < MAX; round++) {
    let took = 0;
    for (const pool of pools) {
      if (round < pool.length) {
        out.push(pool[round]);
        took++;
        if (out.length === MAX) break;
      }
    }
    if (!took) break;
  }
  return out;
};

const bank = {};
for (const [portal, list] of byPortal) bank[portal] = gather(list);

const counts = Object.entries(bank)
  .map(([p, q]) => `${p} ${q.length}`)
  .join(", ");

const file = `/* AUTO-GENERATED by scripts/build-assessment-bank.mjs — do not edit by hand.

   The end-of-portal assessment: up to ${MAX} questions per portal, drawn from
   the lessons' own quizzes and section checks, spread across the lessons so the
   set covers the course rather than one part of it.

   ${counts}. */

export type Bi = { te: string; en: string };

export type AssessmentQuestion = {
  q: Bi;
  options: Bi[];
  answer: number;
  /** Which lesson it came from, so a wrong answer can point somewhere. */
  from: { slug: string; title: Bi };
};

const bank: Record<string, AssessmentQuestion[]> = ${JSON.stringify(bank, null, 1)};

export function assessmentFor(portal: string): AssessmentQuestion[] {
  return bank[portal] ?? [];
}
`;

fs.writeFileSync(OUT, file);
console.log(`Wrote ${path.relative(ROOT, OUT)} — ${counts} (${Math.round(file.length / 1024)} KB)`);
