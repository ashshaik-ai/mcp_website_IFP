const withAudio = (l) => l.filter((x) => x.audio).length;
console.log(`Wrote ${path.relative(ROOT, OUT).split(path.sep).join("/")}`);
console.log(`  arabic: ${arabic.length} letters, ${withAudio(arabic)} with audio`);
console.log(`  urdu:   ${urdu.length} letters, ${withAudio(urdu)} with audio`);
if (missing) console.log(`  ${missing} entries had no matching clip and were set to null`);
