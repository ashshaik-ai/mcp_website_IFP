/* Pull the Arabic and Urdu letter datasets out of the legacy static site.

   Both alphabet lessons declare a `LETTERS` array carrying far more than the
   premium build currently shows: Telugu letter names, transliteration, the
   four positional forms, a pronunciation note in both languages, and the
   filename of a recorded pronunciation clip. The premium build had bare
   glyph + English name and no audio at all.

   The arrays are plain JS literals, so they are evaluated in a vm sandbox
   rather than parsed by regex.

   Usage: node scripts/extract-alphabets.mjs [path-to-static-site]
*/
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = path.resolve(process.argv[2] || "../Islamic Front/projects/islamic-front-website");
const OUT = path.join(ROOT, "src/content/alphabets.ts");

/** Read `var|const|let NAME = [ ... ];` out of a source file and evaluate it. */
function extractArray(file, name) {
  const src = fs.readFileSync(file, "utf8");
  const start = src.search(new RegExp(`(?:var|const|let)\\s+${name}\\s*=\\s*\\[`));
  if (start === -1) throw new Error(`${name} not found in ${file}`);
  const open = src.indexOf("[", start);

  let depth = 0;
  let end = -1;
  let quote = null;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === "\\") i++;
      else if (c === quote) quote = null;
      continue;
    }
    if (c === "'" || c === '"' || c === "`") quote = c;
    else if (c === "[") depth++;
    else if (c === "]") {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end === -1) throw new Error(`Unterminated ${name} in ${file}`);
  return vm.runInNewContext(src.slice(open, end), Object.create(null), { timeout: 3000 });
}

const esc = (s) => JSON.stringify(s ?? "");

/* The legacy site writes alif with hamza and the premium build writes it bare,
   and the two name it differently again ("Bāʾ" vs "ba"). Decomposing and
   dropping the Arabic combining marks reduces both to the same base letter,
   which is the only key that matches across all 28. */
const baseGlyph = (g) =>
  g.normalize("NFD").replace(/[ً-ٰٟۖ-ۭ]/g, "");

function emit(list, script) {
  return list
    .map((l) => {
      const glyph = l.ar ?? l.ur;
      const parts = [
        `    glyph: ${esc(glyph)}`,
        `    name: { te: ${esc(l.name_te)}, en: ${esc(l.name)} }`,
        `    translit: ${esc(l.tr)}`,
        `    forms: { isolated: ${esc(l.iso)}, initial: ${esc(l.ini)}, medial: ${esc(l.med)}, final: ${esc(l.fin)} }`,
        `    note: { te: ${esc(l.note_te)}, en: ${esc(l.note)} }`,
        `    audio: ${l.audio ? esc(`/assets/audio/${script}/${l.audio}.mp3`) : "null"}`,
      ];
      return `  {\n${parts.join(",\n")},\n  },`;
    })
    .join("\n");
}

const arabic = extractArray(path.join(SITE, "knowledge-center/learn-arabic/alphabet.html"), "LETTERS");
const urdu = extractArray(path.join(SITE, "knowledge-center/learn-urdu/alphabet.html"), "LETTERS");

/* An entry claiming audio that is not on disk would render a dead play button. */
let missing = 0;
for (const [list, script] of [
  [arabic, "arabic"],
  [urdu, "urdu"],
]) {
  for (const l of list) {
    if (!l.audio) continue;
    if (!fs.existsSync(path.join(ROOT, "public/assets/audio", script, `${l.audio}.mp3`))) {
      console.warn(`  missing audio: ${script}/${l.audio}.mp3`);
      l.audio = null;
      missing++;
    }
  }
}

const out = `/* AUTO-GENERATED by scripts/extract-alphabets.mjs — do not edit by hand.
   Source: the legacy static site's alphabet lessons. Re-run to refresh.
   Arabic ${arabic.length} letters, Urdu ${urdu.length} letters. */

export type Bi = { te: string; en: string };

export type Letter = {
  glyph: string;
  name: Bi;
  /** Romanised pronunciation. */
  translit: string;
  /** How the letter is written depending on where it sits in a word. */
  forms: { isolated: string; initial: string; medial: string; final: string };
  note: Bi;
  /** Recorded pronunciation, or null when no clip exists. */
  audio: string | null;
};

export const arabicLetters: Letter[] = [
${emit(arabic, "arabic")}
];

export const urduLetters: Letter[] = [
${emit(urdu, "urdu")}
];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");

